"""Render the native CrossLoop vector artwork with the installed ImageMagick CLI."""
from pathlib import Path
import hashlib
import json
import shutil
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SVG_START = '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">'


def ellipse(rx, ry):
    return f'M {256-rx} 256 a {rx} {ry} 0 1 0 {2*rx} 0 a {rx} {ry} 0 1 0 {-2*rx} 0 Z '


# Even-odd fill leaves the four ring intersections transparent.
ORBIT = '<path fill="black" fill-rule="evenodd" d="' + ''.join(
    ellipse(rx, ry) for rx, ry in [(112, 236), (72, 196), (236, 112), (196, 72)]
) + '"/>'

STAR = '<path d="M0 -36 L9 -10 L36 -10 L15 6 L23 32 L0 16 L-23 32 L-15 6 L-36 -10 L-9 -10 Z"/>'
SNOW = '<path fill="none" stroke="black" stroke-width="9" stroke-linecap="round" d="M0 -34 V34 M-29 -17 L29 17 M-29 17 L29 -17"/>'
DECORATIONS = {
    'standard': '',
    'new-year': '<g transform="translate(420 76)">' + STAR + '</g><g transform="translate(80 420) scale(.65)">' + STAR + '</g>',
    'valentine': '<path d="M414 132 C330 75 370 30 414 65 C458 30 498 75 414 132 Z"/>',
    'st-patrick': '<circle cx="418" cy="59" r="25"/><circle cx="391" cy="92" r="25"/><circle cx="445" cy="92" r="25"/><path fill="none" stroke="black" stroke-width="12" d="M418 85 Q432 125 407 149"/>',
    'independence': '<g transform="translate(420 70)">' + STAR + '</g><g transform="translate(365 130) scale(.55)">' + STAR + '</g><g transform="translate(465 155) scale(.55)">' + STAR + '</g>',
    'halloween': '<path d="M355 127 Q420 90 485 127 L466 144 H366 Z M382 112 L407 22 L444 113 Z"/>',
    'thanksgiving': '<path d="M414 39 L428 73 L454 60 L445 92 L478 98 L444 123 L420 123 L410 150 L401 146 L411 119 L385 99 L355 92 L383 79 L378 50 L402 66 Z"/>',
    'winter': '<g transform="translate(418 80)">' + SNOW + '</g><g transform="translate(82 425) scale(.75)">' + SNOW + '</g>',
}


def artwork(name):
    if name == 'standard':
        return SVG_START + ORBIT + '</svg>\n'
    return SVG_START + '<g transform="translate(30 30) scale(.86)">' + ORBIT + '</g>' + DECORATIONS[name] + '</svg>\n'


def main():
    magick = shutil.which('magick')
    if not magick:
        raise SystemExit('ImageMagick is required for this explicit asset-generation step.')
    out = HERE / 'generated'
    out.mkdir(exist_ok=True)
    sources = HERE / 'svg'
    sources.mkdir(exist_ok=True)
    header = ['#pragma once', '#include <cstdint>', '// Generated by personal_features/branding/build_assets.py.']
    records = []
    for name in DECORATIONS:
        src = sources / f'{name}.svg'
        src.write_text(artwork(name), encoding='utf-8')
        png = out / f'{name}-120.png'
        subprocess.run([magick, '-background', 'white', str(src), '-resize', '120x120', '-alpha', 'remove',
                        '-alpha', 'off', '-threshold', '50%', '-type', 'bilevel', str(png)], check=True)
        # PBM encodes black as 1; the renderer's bitmap format uses white as 1.
        pbm = subprocess.check_output([magick, str(png), 'pbm:-'])
        prefix, width, height, body = pbm.split(b'\n', 3) if b'\n120\n120\n' in pbm else (None, None, None, None)
        if body is None:
            magic, dimensions, body = pbm.split(b'\n', 2)
            assert magic == b'P4' and dimensions == b'120 120'
        assert len(body) == 1800
        packed = bytes(value ^ 255 for value in body)
        symbol = ''.join(part.title() for part in name.split('-'))
        header.append(f'inline constexpr uint8_t CROSSLOOP_{symbol.upper()}_120[] = {{')
        header.extend('    ' + ', '.join(f'0x{x:02x}' for x in packed[i:i+20]) + ',' for i in range(0, len(packed), 20))
        header.append('};')
        records.append({'name': name, 'dimensions': [120, 120], 'bytes': len(packed),
                        'svg_sha256': hashlib.sha256(src.read_bytes()).hexdigest(),
                        'bitmap_sha256': hashlib.sha256(packed).hexdigest()})
    (ROOT / 'src/images/CrossLoopLogos.h').write_text('\n'.join(header) + '\n', encoding='utf-8')
    (HERE / 'manifest.json').write_text(json.dumps({'concept': 'Crossed Orbits', 'selected_by': 'Elias',
        'selection_date': '2026-11-08', 'method': 'native SVG artwork; ImageMagick monochrome raster export',
        'assets': records}, indent=2) + '\n', encoding='utf-8')
    for name, width, height in [('x4pro', 480, 800), ('x3', 528, 792)]:
        # Device-size design preview; firmware uses its existing fonts and layout.
        font = ROOT / 'lib/EpdFont/builtinFonts/source/Ubuntu/Ubuntu-Bold.ttf'
        regular = font.with_name('Ubuntu-Regular.ttf')
        subprocess.run([magick, '-size', f'{width}x{height}', 'xc:white',
                        '(', '-background', 'white', str(sources / 'standard.svg'), '-resize', '192x192', '-alpha', 'remove', ')',
                        '-gravity', 'north', '-geometry', f'+0+{height//2-128}', '-composite',
                        '-fill', 'black', '-font', font.as_posix(), '-pointsize', '38',
                        '-gravity', 'north', '-annotate', f'+0+{height//2+76}', 'CrossLoop',
                        '-font', regular.as_posix(), '-pointsize', '19', '-gravity', 'south',
                        '-annotate', '+0+70', 'Starting...', '-threshold', '50%', '-type', 'bilevel',
                        str(out / f'boot-{name}.png')], check=True)
    print(f'Generated {len(records)} monochrome icons and two device-size design previews.')


if __name__ == '__main__':
    main()
